import test from 'node:test'
import assert from 'node:assert/strict'
import {
  buildFrpcConfig,
  frpcConfigFileName,
  hostOfOrigin,
  iniValue,
  portOfOrigin,
  tomlString,
  validateTunnelTarget,
} from '../src/frpc-config.js'

const base = {
  format: 'toml',
  serverAddr: 'vps.example.com',
  serverPort: 7000,
  token: 'secret-token-value',
  tls: true,
  tlsServerName: '',
  localHost: '127.0.0.1',
  localPort: 13162,
  remotePort: 19098,
  proxyName: 'dsh-desktop',
}

test('toml config carries every field frpc needs', () => {
  const text = buildFrpcConfig(base)
  assert.match(text, /^# Generated by dsh-tunnel/)
  assert.match(text, /serverAddr = "vps\.example\.com"/)
  assert.match(text, /serverPort = 7000/)
  assert.match(text, /loginFailExit = false/)
  assert.match(text, /auth\.method = "token"/)
  assert.match(text, /auth\.token = "secret-token-value"/)
  assert.match(text, /transport\.tls\.enable = true/)
  assert.match(text, /\[\[proxies\]\]/)
  assert.match(text, /name = "dsh-desktop"/)
  assert.match(text, /type = "tcp"/)
  assert.match(text, /localIP = "127\.0\.0\.1"/)
  assert.match(text, /localPort = 13162/)
  assert.match(text, /remotePort = 19098/)
  assert.ok(text.endsWith('\n'))
})

test('toml never leaks the token through quote escaping', () => {
  const text = buildFrpcConfig({ ...base, token: 'a"b\\c' })
  assert.match(text, /auth\.token = "a\\"b\\\\c"/)
})

test('the TLS ServerName line appears only when asked for', () => {
  assert.doesNotMatch(buildFrpcConfig(base), /serverName/)
  assert.match(buildFrpcConfig({ ...base, tlsServerName: 'dsh.example.com' }), /transport\.tls\.serverName = "dsh\.example\.com"/)
  assert.doesNotMatch(buildFrpcConfig({ ...base, tls: false }), /transport\.tls\.enable = true/)
})

test('ini config is generated for older frp releases', () => {
  const text = buildFrpcConfig({ ...base, format: 'ini' })
  assert.match(text, /^\[common\]/m)
  assert.match(text, /server_addr = vps\.example\.com/)
  assert.match(text, /token = secret-token-value/)
  assert.match(text, /tls_enable = true/)
  assert.match(text, /login_fail_exit = false/)
  assert.match(text, /^\[dsh-desktop\]$/m)
  assert.match(text, /local_port = 13162/)
  assert.match(text, /remote_port = 19098/)
})

test('generation refuses an incomplete target instead of writing a broken file', () => {
  assert.throws(() => buildFrpcConfig({ ...base, token: '' }), /frp token is not set/)
  assert.throws(() => buildFrpcConfig({ ...base, serverAddr: '  ' }), /server address is empty/)
  assert.throws(() => buildFrpcConfig({ ...base, localPort: 0 }), /local DSH port is unknown/)
  assert.throws(() => buildFrpcConfig({ ...base, proxyName: 'bad name' }), /proxy name is invalid/)
  assert.deepEqual(validateTunnelTarget(base), [])
})

test('origin helpers read the ports DSH actually bound', () => {
  assert.equal(portOfOrigin('http://127.0.0.1:13162'), 13162)
  assert.equal(portOfOrigin('http://127.0.0.1'), 80)
  assert.equal(portOfOrigin('https://127.0.0.1'), 443)
  assert.equal(portOfOrigin(''), 0)
  assert.equal(portOfOrigin('not a url'), 0)
  assert.equal(hostOfOrigin('http://[::1]:3080'), '::1')
  assert.equal(hostOfOrigin(''), '127.0.0.1')
})

test('string encoders escape what would corrupt each format', () => {
  assert.equal(tomlString('a\nb'), '"a\\nb"')
  assert.equal(tomlString('a\u0001b'), '"a\\u0001b"')
  assert.equal(tomlString(undefined), '""')
  assert.equal(iniValue('a\nb'), 'a b')
})

test('the generated config file name follows the format', () => {
  assert.equal(frpcConfigFileName('toml'), 'frpc.toml')
  assert.equal(frpcConfigFileName('ini'), 'frpc.ini')
  assert.equal(frpcConfigFileName('anything'), 'frpc.toml')
})
